#pragma once

#include "lvgl.h"

/* ============================================================
 *  Remote_Fonts.h
 *  Централизованная карта шрифтов для UI.
 *
 *  Файл определяет, какие именно шрифты LVGL
 *  используются для конкретных ролей интерфейса
 *  (имя устройства, окна, оверлеи, селекторы).
 *
 *  ВАЖНО:
 *  - Шрифты НЕ масштабируются динамически.
 *  - Изменение макроса влияет на ВСЕ элементы,
 *    использующие эту роль.
 * ============================================================*/

/* ------------------------------------------------------------
 * Основные шрифты UI (главный экран лампы)
 * ------------------------------------------------------------ */

/* Имя устройства в центральном окне (самый крупный текст) */
#define J_FONT_DEVICE_NAME   (&lv_font_montserrat_36)

/* Небольшие заголовки (окно комнаты, вторичные подписи) */
#define J_FONT_SMALL_TITLE   (&lv_font_montserrat_18)

/* Основной текст (температура, мощность, значения) */
#define J_FONT_BODY          (&lv_font_montserrat_20)

/* ------------------------------------------------------------
 * Оверлеи и крупные заголовки (полноэкранные окна)
 * ------------------------------------------------------------ */

/* Текст в полноэкранных оверлеях (яркость, скорость) */
#define J_FONT_OVERLAY       (&lv_font_montserrat_28)

/* Заголовок диагностического экрана */
#define J_FONT_DIAG_TITLE    (&lv_font_montserrat_24)

/* Обычный текст диагностического экрана */
#define J_FONT_DIAG_TEXT     (&lv_font_montserrat_16)

/* ------------------------------------------------------------
 * Шрифты колеса анимаций
 * Используются в изогнутом селекторе анимаций
 * ------------------------------------------------------------ */

/* Самые дальние элементы (минимальный акцент) */
#define J_WHEEL_FONT_14      (&lv_font_montserrat_14)

/* Малый размер элементов */
#define J_WHEEL_FONT_18      (&lv_font_montserrat_18)

/* Средний размер (ближе к центру) */
#define J_WHEEL_FONT_22      (&lv_font_montserrat_22)

/* Крупные элементы (активные / почти активные) */
#define J_WHEEL_FONT_28      (&lv_font_montserrat_28)

/* ------------------------------------------------------------
 * Крупные шрифты колеса (зависят от конфигурации LVGL)
 * ------------------------------------------------------------ */

/* Логический размер ~34px, фактически используется 32px */
#define J_WHEEL_FONT_34      (&lv_font_montserrat_32)

/* Максимальный размер шрифта для центрального элемента */
#define J_WHEEL_FONT_40      (&lv_font_montserrat_40)
